/**
 * Mendapatkan SVG sebagai data URL untuk dimuat di Phaser preload
 */
export function getSvgDataUrl(key) {
  const svg = SVG_ASSETS[key];
  if (!svg) return null;
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

/**
 * Memuat semua tekstur SVG ke scene Phaser melalui load pipeline native.
 * Dipanggil di dalam preload() scene.
 */
export function preloadAllSvgTextures(scene) {
  for (const [key, svgStr] of Object.entries(SVG_ASSETS)) {
    if (!scene.textures.exists(key)) {
      const dataUrl = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svgStr);
      scene.load.image(key, dataUrl);
    }
  }
}

